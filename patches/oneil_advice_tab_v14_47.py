# v14.47 — 오닐의 한마디 탭 (개별종목 옆)
# RARS·종합등급 RS·RSI 차이 설명 + 오늘의 할일 / 보유 시 / 신규투자 시

ONEIL_ADVICE_TAB = True

def render_oneil_advice_tab():
    st.header("오닐의 한마디")
    st.caption("앱 지표를 어떻게 해석하고 행동에 옮길지 정리한 안내입니다. 매수 권유가 아닙니다.")

    st.subheader("지표 차이 한눈에")
    st.markdown("""
| 지표 | 보는 것 | 해석 |
|------|---------|------|
| **종합등급 RS / 앱 RS 대리** | 주로 1년 수익률 | 장기 상대강도 대리. 높을수록 과거부터 강한 편 |
| **RARS 기본** | 1m 22% · 3m 48% · 6m 22% · 12m 8% + 가속도 | 최근 모멘텀·가속도. 지금 강해지는 종목 |
| **RARS + 변동성** | 기본 + 6개월 최대낙폭 감점 | 급락 종목을 더 보수적으로 |
| **SPY 대비 초과** | 동일 가중치로 시장 대비 | 시장을 이겼는가 |
| **RSI** | 최근 14일 상승/하락 폭 비율 | 단기 과매수(70+)·과매도(30-) |

**핵심**: 종합등급 RS는 *장기 품질*, RARS는 *최근 모멘텀*, RSI는 *단기 과열*입니다. 섞어서 같은 의미로 보지 마세요.
    """)

    col1, col2, col3 = st.columns(3)

    with col1:
        st.markdown("### 오늘의 할일")
        st.markdown("""
- 시장 노출(Exposure)과 분산일 수를 먼저 확인
- 관심 종목의 **RARS 기본**과 **RARS+변동성**을 비교
- RARS는 높은데 변동성 버전이 크게 낮으면 최근 급락 여부 점검
- SPY 대비 초과가 플러스인지 확인
- 실적 일정이 14일 이내면 신규 매수 자제
- 베이스·피벗 위치가 유효한지 확인
        """)

    with col2:
        st.markdown("### 보유하고 있다면")
        st.markdown("""
- **RARS 기본이 높고 변동성 패널티가 작다** → 보유 유지, 추가 매수는 시장·자리 확인 후
- **종합등급 RS는 높은데 RARS가 낮다** → 과거 좋았지만 최근 모멘텀 약화. 추가 매수 금지, 손절·부분매도 기준 점검
- **RARS가 급락** → 최근 조정·급락 가능성. 8% 손절 규칙과 베이스 이탈 여부 확인
- 실적 발표가 임박하면 포지션 크기 조절
- 시장이 분산일 누적·노출 축소 국면이면 이익 종목도 리밸런싱 고려
        """)

    with col3:
        st.markdown("### 신규투자한다면")
        st.markdown("""
- **1차 필터**: RARS 기본 ≥ 75~80 이고 RARS+변동성도 크게 떨어지지 않을 것
- **시장 대비**: SPY 대비 초과가 플러스일 것
- **교차 확인**: 종합등급 RS(장기)도 중간 이상이면 더 좋음
- **자리**: 베이스 안 또는 피벗 근처, 추격 매수 금지
- **시장**: Exposure가 허용 구간이고 분산일이 과도하지 않을 것
- RSI가 70 이상이면 단기 과열 가능성 → 추격 자제
- 실적 14일 이내면 신규 진입 보류
        """)

    st.divider()
    st.info("""
**한 줄 정리**  
- 종합등급 RS → 장기 리더십 확인  
- RARS → 지금 강해지는지 확인  
- RSI → 단기 과열 여부만 참고  

셋 다 앱 자체 계산입니다. IBD 공식 수치와 다르며, 단독 매수 신호로 쓰지 마세요. 시장 국면·실적·베이스 위치와 함께 보세요.
    """)

# Inject the tab
if "TABS" in globals() and len(TABS) > 13:
    with TABS[14], guard("오닐의 한마디"):
        render_oneil_advice_tab()
